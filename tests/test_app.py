def test_signup_rejects_activity_at_capacity(client):
    # Arrange
    activity_name = "Soccer Club"
    activity = activities[activity_name]
    activity["max_participants"] = 1
    activity["participants"] = ["registered@mergington.edu"]

    # Act
    response = client.post(
        f"/activities/{activity_name}/signup",
        params={"email": "student@mergington.edu"},
    )

    # Assert
    assert response.status_code == 400
    assert response.json()["detail"] == "Activity is full"
    assert activity["participants"] == ["registered@mergington.edu"]


def test_signup_accepts_participant_when_one_spot_remains(client):
    # Arrange
    activity_name = "Soccer Club"
    activity = activities[activity_name]
    activity["max_participants"] = 2
    activity["participants"] = ["registered@mergington.edu"]
    email = "student@mergington.edu"

    # Act
    response = client.post(
        f"/activities/{activity_name}/signup",
        params={"email": email},
    )

    # Assert
    assert response.status_code == 200
    assert activity["participants"] == ["registered@mergington.edu", email]


def test_remove_participant(client):
    # Arrange
    activity_name = "Chess Club"
    email = "michael@mergington.edu"

    # Act
    response = client.delete(
        f"/activities/{activity_name}/participants",
        params={"email": email},
    )

    # Assert
    assert response.status_code == 200
    assert response.json() == {"message": f"Removed {email} from {activity_name}"}
    assert email not in activities[activity_name]["participants"]


